"""Resolve the Espressif port Kconfig and write CMake assignments.

Inputs are KEY=value files. Bool values may be y/n (Kconfig) or 1/0 (legacy
.conf fragments). Later files override earlier ones. The saved mcuboot.conf
is applied last when requested, so a menuconfig session is kept.
"""

import argparse
import os
import re
import sys


def load_kconfiglib():
    """Return the kconfiglib implementation available in this interpreter.

    ESP-IDF's Python environment exposes a kconfiglib shim that does not
    re-export the type constants. Those live on esp_kconfiglib.core, which is
    the same library. A standalone install of upstream kconfiglib is used
    when it provides them directly.
    """
    try:
        import kconfiglib
    except ImportError:
        kconfiglib = None
    if kconfiglib is not None and hasattr(kconfiglib, "BOOL"):
        return kconfiglib
    try:
        import esp_kconfiglib.core as core
    except ImportError:
        core = None
    if core is not None and hasattr(core, "BOOL") and hasattr(core, "Kconfig"):
        return core
    sys.stderr.write(
        "error: kconfiglib is required. Install it with: "
        "python3 -m pip install -r boot/espressif/tools/requirements.txt\n"
    )
    raise SystemExit(1)


kconfiglib = load_kconfiglib()
BOOL_TYPES = (kconfiglib.BOOL,)
if hasattr(kconfiglib, "TRISTATE"):
    BOOL_TYPES = (kconfiglib.BOOL, kconfiglib.TRISTATE)

ASSIGN_RE = re.compile(r"^(CONFIG_[A-Za-z0-9_]+)=(.*)$")
UNSET_RE = re.compile(r"^# (CONFIG_[A-Za-z0-9_]+) is not set$")


def symbol_name(config_name):
    prefix = "CONFIG_"
    if config_name.startswith(prefix):
        return config_name[len(prefix):]
    return config_name


def parse_conf(path):
    """Return (name, raw_value, line) pairs. raw_value is None when the symbol is unset."""
    entries = []
    with open(path, encoding="utf-8") as conf_file:
        for line_number, raw_line in enumerate(conf_file, start=1):
            line = raw_line.strip()
            if not line:
                continue
            unset = UNSET_RE.match(line)
            if unset:
                entries.append((symbol_name(unset.group(1)), None, line_number))
                continue
            if line.startswith("#"):
                continue
            assignment = ASSIGN_RE.match(line.split("#", 1)[0].strip())
            if not assignment:
                print(
                    f"warning: {path}:{line_number}: ignored line: {raw_line.rstrip()}",
                    file=sys.stderr,
                )
                continue
            value = assignment.group(2).strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
                value = value[1:-1]
            entries.append((symbol_name(assignment.group(1)), value, line_number))
    return entries


def value_for_symbol(sym, raw_value):
    if raw_value is None:
        if sym.orig_type in BOOL_TYPES:
            return "n"
        return None
    if sym.orig_type in BOOL_TYPES:
        if raw_value in ("y", "Y", "1"):
            return "y"
        if raw_value in ("n", "N", "0"):
            return "n"
        return None
    return raw_value


def apply_entries(kconf, path, entries):
    # Two passes so a symbol can be set after the one it depends on,
    # regardless of order inside the file.
    for pass_index in range(2):
        for name, raw_value, line_number in entries:
            sym = kconf.syms.get(name)
            if sym is None:
                if pass_index == 0:
                    print(
                        f"warning: {path}:{line_number}: unknown symbol CONFIG_{name}",
                        file=sys.stderr,
                    )
                continue
            value = value_for_symbol(sym, raw_value)
            if value is None:
                if pass_index == 0:
                    print(
                        f"warning: {path}:{line_number}: "
                        f"cannot assign {raw_value!r} to CONFIG_{name}",
                        file=sys.stderr,
                    )
                continue
            if pass_index == 1 and not sym.set_value(value):
                print(
                    f"warning: {path}:{line_number}: CONFIG_{name}={value} was not applied",
                    file=sys.stderr,
                )
            elif pass_index == 0:
                sym.set_value(value)


def cmake_string(value):
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def write_cmake(kconf, path):
    lines = [
        "# Generated by kconfig_gen.py. Do not edit.",
        "",
    ]
    for sym in kconf.unique_defined_syms:
        if getattr(sym, "env", None) or sym.visibility == 0:
            continue
        name = f"CONFIG_{sym.name}"
        if sym.orig_type in BOOL_TYPES:
            if sym.str_value != "y":
                continue
            lines.append(f"set({name} 1)")
            lines.append(f"add_compile_definitions({name}=1)")
        elif sym.orig_type in (kconfiglib.INT, kconfiglib.HEX):
            lines.append(f"set({name} {sym.str_value})")
            lines.append(f"add_compile_definitions({name}={sym.str_value})")
        elif sym.orig_type == kconfiglib.STRING:
            if sym.str_value == "":
                continue
            lines.append(f"set({name} {cmake_string(sym.str_value)})")
        else:
            continue
    lines.append("")
    with open(path, "w", encoding="utf-8") as cmake_file:
        cmake_file.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(
        description="Generate the MCUboot Espressif port configuration"
    )
    parser.add_argument("--kconfig", required=True)
    parser.add_argument("--target", required=True)
    parser.add_argument("--defaults", required=True)
    parser.add_argument("--fragment", action="append", default=[])
    parser.add_argument(
        "--config",
        required=True,
        help="Resolved configuration written for menuconfig",
    )
    parser.add_argument("--cmake", required=True, help="CMake assignments included by the build")
    parser.add_argument(
        "--load-saved",
        action="store_true",
        help="Apply the existing --config file after defaults and fragments",
    )
    args = parser.parse_args()

    os.environ["MCUBOOT_TARGET"] = args.target
    kconf = kconfiglib.Kconfig(args.kconfig, warn=False)

    sources = [args.defaults] + list(args.fragment)
    for path in sources:
        if not os.path.isfile(path):
            print(f"error: configuration file not found: {path}", file=sys.stderr)
            return 1
        apply_entries(kconf, path, parse_conf(path))

    if args.load_saved and os.path.isfile(args.config):
        apply_entries(kconf, args.config, parse_conf(args.config))

    os.makedirs(os.path.dirname(os.path.abspath(args.config)), exist_ok=True)
    kconf.write_config(args.config, header="# Generated by kconfig_gen.py. Edit with menuconfig.\n")
    write_cmake(kconf, args.cmake)
    return 0


if __name__ == "__main__":
    sys.exit(main())
